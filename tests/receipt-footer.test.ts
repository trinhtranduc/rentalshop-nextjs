/**
 * #1593 owner: the last line of a printed bill says the bill was made with AnyRent,
 * not "Download AnyRent on App Store" (wrong on Android, and an ad on the shop's paper).
 * Web slip, iOS thermal print and Android thermal print say the same sentence.
 */
import * as fs from 'fs';
import * as path from 'path';

const root = path.resolve(__dirname, '..');
const read = (file: string) => fs.readFileSync(path.join(root, file), 'utf8');
const json = (file: string) => JSON.parse(read(file));

const VI = 'Hóa đơn được tạo bằng ứng dụng AnyRent';
const IOS_KEY = 'Receipt generated by AnyRent software';
const IOS = 'apps/mobile/POS ADBD';
const ANDROID = 'apps/mobile-android/app/src/main';

const strings = (file: string) =>
  Object.fromEntries([...read(file).matchAll(/^"((?:[^"\\]|\\.)+)"\s*=\s*"((?:[^"\\]|\\.)*)";/gm)].map((m) => [m[1], m[2]]));
const androidString = (file: string, name: string) =>
  read(file).match(new RegExp(`<string name="${name}"[^>]*>([^<]*)</string>`))?.[1];

// web locale → iOS folder holding the same language
const WEB_TO_IOS: Record<string, string> = {
  vi: 'vi-VN', en: 'en', ja: 'ja', ko: 'ko', zh: 'zh-Hans', 'zh-TW': 'zh-Hant',
  fr: 'fr', de: 'de', ru: 'ru', th: 'th', id: 'id', es: 'es',
};

describe('#1593 bill footer', () => {
  it('web slip prints orders.web.receipt.generatedBy, the iOS sentence in every language', () => {
    const slip = read('apps/client/app/orders/receipt/ReceiptSlip.tsx');
    expect(slip).toContain("t('generatedBy')");
    expect(slip).not.toContain("t('downloadApp')");
    for (const [lang, iosLang] of Object.entries(WEB_TO_IOS)) {
      const receipt = json(`locales/${lang}/orders.json`).web.receipt;
      const expected = strings(`${IOS}/${iosLang}.lproj/Localizable.strings`)[IOS_KEY];
      expect({ lang, generatedBy: receipt.generatedBy, downloadApp: receipt.downloadApp }).toEqual({
        lang, generatedBy: expected, downloadApp: undefined,
      });
    }
    expect(json('locales/vi/orders.json').web.receipt.generatedBy).toBe(VI);
  });

  it('iOS thermal print ends with the generated-by line, Vietnamese text is the new sentence', () => {
    const order = read(`${IOS}/Model/Order.swift`);
    expect(order).toContain(`"${IOS_KEY}".localized().formatStringOriginalCharacter()`);
    expect(order).not.toContain('"Download AnyRent on App Store"');
    expect(strings(`${IOS}/vi-VN.lproj/Localizable.strings`)[IOS_KEY]).toBe(VI);
  });

  it('Android thermal print uses receipt_generated_by in the app language, not a hard-coded App Store line', () => {
    const printer = read(`${ANDROID}/java/com/anyrent/pos/print/ThermalPrinter.kt`);
    expect(printer).toContain('R.string.receipt_generated_by');
    expect(printer).not.toContain('App Store');
    expect(androidString(`${ANDROID}/res/values-vi/strings.xml`, 'receipt_generated_by')).toBe(VI);
  });
});
